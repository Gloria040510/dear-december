const preferenceKey = 'dear-december-language';

export function initialLanguage(): Language {
  try {
    const saved = localStorage.getItem(preferenceKey);
    if (saved === 'en' || saved === 'zh-CN') return saved;
  } catch { /* Storage may be disabled in a private or embedded browser. */ }
  return navigator.language.toLowerCase().split('-')[0] === 'zh' ? 'zh-CN' : 'en';
}

export function rememberLanguage(language: Language) {
  try { localStorage.setItem(preferenceKey, language); } catch { /* The current session can still switch language. */ }
}

